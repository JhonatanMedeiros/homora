/** Como um valor de ícone será desenhado. */
export function iconKind(value: string): 'empty' | 'lucide' | 'image' | 'text' {
  if (!value) return 'empty';
  if (value.startsWith('lucide:')) return 'lucide';
  if (/^https?:\/\//i.test(value)) return 'image';
  return 'text';
}
